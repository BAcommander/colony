"""Freeze the approved V6 inputs and generate the explicitly adapted native loop renderer.

The snapshot stays byte-exact. Every textual adaptation below fails closed if the
approved renderer changes, making the resolution/period changes reviewable.
"""
from pathlib import Path
import hashlib, json, shutil

H=Path(__file__).resolve().parent
SOURCE=H.parents[1]/'below-the-snowline-animation-v6'
SNAP=H/'source-snapshot'

def sha(p):
    with p.open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()

def main():
    SNAP.mkdir(parents=True,exist_ok=True)
    names=['render_v6.py','source.png','v2-scene.json','geometry-v6.json','events.json',
           'assets/lambda-shuttle-master.png','user-approval.json','audit_flight.py']
    records=[]
    for name in names:
        src,dst=SOURCE/name,SNAP/name
        dst.parent.mkdir(parents=True,exist_ok=True)
        if dst.exists():assert sha(dst)==sha(src),name
        else:shutil.copyfile(src,dst)
        records.append({'file':name,'source':str(src),'sha256':sha(dst),'bytes':dst.stat().st_size})
    code=(SNAP/'render_v6.py').read_text(encoding='utf-8')
    def change(old,new):
        nonlocal code
        assert old in code,repr(old)
        code=code.replace(old,new)
    change('"""Snowline V6: a continuous two-minute weather/base-activity review, not a tiled loop."""',
           '"""Native 1672x941 adaptation of approved V6; true forward-moving 120s loop. Generated by prepare_native.py."""')
    change('H=Path(__file__).resolve().parent\nROOT=H.parents[1]\nW,HEIGHT,FPS=1280,720,30',
           'JOB=Path(__file__).resolve().parent\nH=JOB/"source-snapshot"\nROOT=JOB.parents[2]\nW,HEIGHT,FPS=1672,941,30\nPERIOD=120.0\nR=1672/1280\nRY=941/720\nANCHOR=48.0')
    change('def point(x,y):', '''def omega(w):
    return 2*np.pi*max(1,round(abs(w)*PERIOD/(2*np.pi)))/PERIOD*np.sign(w)
def phase(t,w):
    # Match approved V6 phase at 48s while making a whole number of cycles.
    return omega(w)*(t-ANCHOR)+w*ANCHOR
def period(p):return PERIOD/max(1,round(PERIOD/p))
def point(x,y):''')
    change('smooth((self.cloud_distance-4)/8)','smooth((self.cloud_distance-4*R)/(8*R))')
    change('0,4,cv2.LINE_AA','0,round(4*R),cv2.LINE_AA')
    change('0,3,cv2.LINE_AA','0,round(3*R),cv2.LINE_AA')
    change('hh=round(width*asset.shape[0]/asset.shape[1])\n            rgba=cv2.resize(asset,(width,hh),interpolation=cv2.INTER_AREA)',
           'native_width=round(width*R);hh=round(native_width*asset.shape[0]/asset.shape[1])\n            rgba=cv2.resize(asset,(native_width,hh),interpolation=cv2.INTER_AREA)')
    # Preserve the event shape over the seam: the second gust naturally carries
    # into the next period. No wind fade is imposed on the entire scene.
    change("return max([0.0]+[pulse(t,e['start'],e['end'],e['rise'],e['fall']) for e in self.wind_events])",
           "return max([0.0]+[pulse(t+offset,e['start'],e['end'],e['rise'],e['fall']) for e in self.wind_events for offset in [-PERIOD,0,PERIOD]])")
    change('self.x[y0:y1,x0:x1]/scale[0]*256-speed*t',
           'self.x[y0:y1,x0:x1]/(scale[0]*R)*256-(256*max(1,round(speed*PERIOD/256))/PERIOD*(t-ANCHOR)+speed*ANCHOR)')
    change('self.y[y0:y1,x0:x1]/scale[1]*128+3*np.sin(t/19)',
           'self.y[y0:y1,x0:x1]/(scale[1]*RY)*128+3*np.sin(phase(t,1/19))')
    replacements={
      'u*8-t*.8+phase':'u*8-globals()["phase"](t,.8)+phase',
      '(1.2+ww*u)':'(1.2*R+ww*u)',
      'u*15-t*1.4+phase':'u*15-globals()["phase"](t,1.4)+phase',
      'u*27-t*2.3':'u*27-globals()["phase"](t,2.3)',
      '(t-i*7.2)%37':'(t-i*7.2)%period(37)',
      "(t-c['phase'])%19":"(t-c['phase'])%period(19)",
      'np.sin(t*4)**2':'np.sin(phase(t,4))**2',
      '(t-i*.9)%17':'(t-i*.9)%period(17)',
      '(t-i*3.1)%43':'(t-i*3.1)%period(43)',
      't/(2.7+i*.65)+i':'phase(t,1/(2.7+i*.65))+i',
      'i*1.7+t/(50+i*20)':'i*1.7+phase(t,1/(50+i*20))',
      't*1.1+i':'phase(t,1.1)+i',
      'self.y[b:d,a:z]*1.4-t*(1+i*.23)':'self.y[b:d,a:z]/RY*1.4-phase(t,1+i*.23)',
      'np.sin(t/10.7)':'np.sin(phase(t,1/10.7))',
      'u*8-t*1.4':'u*8-phase(t,1.4)',
      'u*13-t*.9':'u*13-phase(t,.9)',
      '(1+4*S[0]*np.maximum(u,0))':'(R+4*S[0]*np.maximum(u,0))',
      'u*19-t*1.8':'u*19-phase(t,1.8)',
      'head,2,fade':'head,round(2*R),fade',
      'fade,3,cv2.LINE_AA':'fade,round(3*R),cv2.LINE_AA',
      't*4.5+phase':'globals()["phase"](t,4.5)+phase',
      'np.sin(t*1.8+i)**2':'np.sin(phase(t,1.8)+i)**2',
      "(t+c['phase'])%c['period']":"(t+c['phase'])%period(c['period'])",
      'radius=35':'radius=round(35*R)',
      '2*6**2':'2*(6*R)**2',
      '2*2.1**2':'2*(2.1*R)**2',
      'self.cloud_distance[b:d,a:z]/45':'self.cloud_distance[b:d,a:z]/(45*R)',
      '11*np.sin(t/31)+1.0*np.sin(t/13+yy/170)':'11*R*np.sin(phase(t,1/31))+R*np.sin(phase(t,1/13)+yy/(170*RY))',
      '2.1*np.sin(t/37+xx/310)':'2.1*RY*np.sin(phase(t,1/37)+xx/(310*R))',
      'np.sin(t/18+self.x/W*2)':'np.sin(phase(t,1/18)+self.x/W*2)',
    }
    for old,new in replacements.items():change(old,new)
    # Exhaust is expressed in its original 720p pixels; scale the whole local
    # coordinate field while retaining the native sprite's premultiplied alpha.
    change('x0=int(np.floor(left))-24;y0=int(np.floor(top))-12',
           'padx=round(24*R);pady=round(12*RY);x0=int(np.floor(left))-padx;y0=int(np.floor(top))-pady')
    change('bw,bh=ww+48,hh+24','bw,bh=ww+2*padx,hh+2*pady')
    change('left-np.floor(left)+24','left-np.floor(left)+padx')
    change('top-np.floor(top)+12','top-np.floor(top)+pady')
    change('ex=24+engine_x','ex=padx+engine_x')
    change('ey=12+v*hh','ey=pady+v*hh')
    change('(ex-xx)*direction','(ex-xx)/R*direction')
    change('np.sin(t*2.6+k)','np.sin(phase(t,2.6)+k)')
    change('centre=ey+.25*np.sin(back*.65-t*4+k)','centre=ey/RY+.25*np.sin(back*.65-phase(t,4)+k)')
    change('(yy-centre)/spread','(yy/RY-centre)/spread')
    change('((xx-ex)**2+(yy-ey)**2)','(((xx-ex)/R)**2+((yy-ey)/RY)**2)')
    # Radius/stroke-dependent snow is calculated in native pixels. Positive
    # integer traversals close each particle's torus without reversing motion.
    start=code.index('        # Snow travels continuously;')
    end=code.index('        self.hardware(f,t)',start)
    code=code[:start]+'''        self.snow_layer(f,t,gust)
'''+code[end:]
    method='''    def snow_positions(self,t):
        for sx,sy,vx,vy,r,opacity,p in self.flakes:
            spanx=W+80*R;spany=HEIGHT+50*RY
            nominal_x=vx*1.08;nominal_y=vy
            ratex=max(1,round(nominal_x*PERIOD/spanx))*spanx/PERIOD
            ratey=max(1,round(nominal_y*PERIOD/spany))*spany/PERIOD
            x=(sx+ratex*(t-ANCHOR)+nominal_x*ANCHOR+vx*2.2*np.sin(phase(t,1/13))+8*R*np.sin(phase(t,1/7)+p))%spanx-40*R
            y=(sy+ratey*(t-ANCHOR)+nominal_y*ANCHOR+4*RY*np.sin(phase(t,1/5)+p))%spany-25*RY
            yield x,y,r,opacity

    def snow_layer(self,f,t,gust):
        snow=np.zeros((HEIGHT,W),np.uint8)
        for x,y,r,opacity in self.snow_positions(t):
            amount=opacity*(.35+.65*gust)
            fade=float(smooth((x-275*R)/(35*R))*smooth((1250*R-x)/(30*R))*smooth((y+5*RY)/(25*RY))*smooth((570*RY-y)/(35*RY)))
            value=int(255*amount*fade)
            if value<2 or y<0 or y>=HEIGHT or x<0 or x>=W:continue
            trail=(1+gust*4)*(r/.8)*R
            cv2.line(snow,(round(x),round(y)),(round(x-trail),round(y-trail*.28)),value,round(R) if r<1.1 else round(2*R),cv2.LINE_AA)
        snow=cv2.GaussianBlur(snow,(3,3),.45*R).astype(np.float32)/255
        self.blend(f,[231,241,249],snow*self.glass)

'''
    code=code.replace('    def frame(self,t):',method+'    def frame(self,t):\n        t=float(t)%PERIOD')
    # Keep the frozen accepted renderer's source-only entry point out of the
    # production interface; production.py owns samples, audits and encoding.
    code=code[:code.index('\ndef encode_segment(index):')]
    (H/'render_native.py').write_text(code,encoding='utf-8')
    (H/'source-manifest.json').write_text(json.dumps({'status':'frozen','source_version':'approved V6','files':records,'native_dimensions':[1672,941],'generated_renderer_sha256':sha(H/'render_native.py'),'period_seconds':120,'reference_phase_seconds':48},indent=2),encoding='utf-8')
    print('Frozen inputs and generated native renderer',flush=True)

if __name__=='__main__':main()
